import { Kysely, PostgresDialect } from 'kysely';
import { Pool, type PoolConfig } from 'pg';
import { dbLogger } from '@/lib/logger';
import type { DB } from './database.types';

const poolConfig: PoolConfig = {
    connectionString: process.env.DATABASE_URL,
    max: Number(process.env.DATABASE_POOL_MAX) || 10,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 5000,
};

declare global {
    // eslint-disable-next-line no-var
    var __mtms_pg_pool: Pool | undefined;
    // eslint-disable-next-line no-var
    var __mtms_kysely_db: Kysely<DB> | undefined;
}

let pool: Pool;
if (globalThis.__mtms_pg_pool) {
    pool = globalThis.__mtms_pg_pool;
} else {
    pool = new Pool(poolConfig);
    // Critical safeguard: prevent unhandled idle client errors from crashing the Node.js process
    pool.on('error', (err) => {
        dbLogger.error('Unexpected error on idle PostgreSQL client in pool', err);
    });
    if (process.env.NODE_ENV !== 'production') {
        globalThis.__mtms_pg_pool = pool;
    }
}

let dbInstance: Kysely<DB>;
if (globalThis.__mtms_kysely_db) {
    dbInstance = globalThis.__mtms_kysely_db;
} else {
    const dialect = new PostgresDialect({ pool });
    dbInstance = new Kysely<DB>({ dialect });
    if (process.env.NODE_ENV !== 'production') {
        globalThis.__mtms_kysely_db = dbInstance;
    }
}

// Database interface is generated by kysely-codegen
export const db = dbInstance;
export { pool };
