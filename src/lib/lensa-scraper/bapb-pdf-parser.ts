import zlib from 'node:zlib';

export interface BapbPdfHeader {
    no_bapm?: string;
    id_project?: string;
    nama_project?: string;
    nama_gudang?: string;
    alamat?: string;
    mitra?: string;
    lokasi_project?: string;
    tanggal?: string;
    nik_petugas?: string;
    nama_petugas?: string;
    jabatan_petugas?: string;
}

export interface BapbPdfMaterial {
    NO: string;
    'ID MATERIAL': string;
    'NAMA MATERIAL': string;
    SATUAN: string;
    'QTY PEMAKAIAN': string;
    KETERANGAN: string;
}

export interface BapbPdfParseResult {
    header: BapbPdfHeader;
    materials: BapbPdfMaterial[];
}

interface PdfTextBlock {
    text: string;
    x: number;
    y: number;
}

/**
 * Extracts positioned text blocks from TCPDF streams using native zlib.
 * Zero external npm dependencies.
 */
export function extractTextBlocksFromPdf(pdfBuffer: Buffer): PdfTextBlock[] {
    const blocks: PdfTextBlock[] = [];
    let pos = 0;

    while ((pos = pdfBuffer.indexOf(Buffer.from('stream'), pos)) !== -1) {
        pos += 6;
        if (pdfBuffer[pos] === 0x0d) pos++;
        if (pdfBuffer[pos] === 0x0a) pos++;
        const end = pdfBuffer.indexOf(Buffer.from('endstream'), pos);
        if (end === -1) break;

        const rawStream = pdfBuffer.subarray(pos, end);
        pos = end + 9;

        let content = '';
        try {
            content = zlib.inflateSync(rawStream).toString('latin1');
        } catch (_e) {
            continue;
        }

        const btBlocks = content.match(/BT[\s\S]*?ET/g) || [];
        for (const bt of btBlocks) {
            let x = 0;
            let y = 0;
            const tdMatch = bt.match(/([-\d.]+)\s+([-\d.]+)\s+Td/);
            const tmMatch = bt.match(
                /([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+Tm/
            );

            if (tdMatch) {
                x = parseFloat(tdMatch[1]);
                y = parseFloat(tdMatch[2]);
            } else if (tmMatch) {
                x = parseFloat(tmMatch[5]);
                y = parseFloat(tmMatch[6]);
            }

            const strParts: string[] = [];
            const tjRegex = /\((.*?)\)/g;
            let m: RegExpExecArray | null = tjRegex.exec(bt);
            while (m !== null) {
                const unescaped = m[1].replace(/\\([()\\])/g, '$1');
                strParts.push(unescaped);
                m = tjRegex.exec(bt);
            }

            const str = strParts.join('').trim();
            if (str) {
                blocks.push({
                    text: str,
                    x: Math.round(x),
                    y: Math.round(y),
                });
            }
        }
    }

    blocks.sort((a, b) => {
        const yDiff = b.y - a.y;
        if (Math.abs(yDiff) > 3) return yDiff;
        return a.x - b.x;
    });

    return blocks;
}

/**
 * Parses BAPB / BAPM PDF buffer generated by TCPDF into structured header & material items.
 */
export function parseBapbPdfBuffer(pdfBuffer: Buffer): BapbPdfParseResult {
    const blocks = extractTextBlocksFromPdf(pdfBuffer);

    // Group blocks into horizontal lines
    const lines: { y: number; items: PdfTextBlock[] }[] = [];
    let currentLine: PdfTextBlock[] = [];
    let currentY: number | null = null;

    for (const b of blocks) {
        if (currentY === null || Math.abs(b.y - currentY) > 3) {
            if (currentLine.length > 0 && currentY !== null) {
                lines.push({ y: currentY, items: currentLine });
            }
            currentLine = [b];
            currentY = b.y;
        } else {
            currentLine.push(b);
        }
    }
    if (currentLine.length > 0 && currentY !== null) {
        lines.push({ y: currentY, items: currentLine });
    }

    const header: BapbPdfHeader = {};
    const rawRows: { y: number; items: PdfTextBlock[] }[] = [];
    let inTable = false;

    for (const line of lines) {
        const lineText = line.items.map((it) => it.text).join(' ');

        if (lineText.includes('No BAPM')) {
            const m = lineText.match(/No BAPM\s*:\s*(\S+)/);
            if (m) header.no_bapm = m[1];
        }
        if (lineText.includes('ID Project')) {
            const m = lineText.match(/ID Project\s*:\s*(\S+)/);
            if (m) header.id_project = m[1];
        }
        if (lineText.includes('Nama Project')) {
            const m = lineText.match(/Nama Project\s*:\s*(.+)$/);
            if (m) header.nama_project = m[1].trim();
        }
        if (lineText.includes('Nama Gudang')) {
            const m = lineText.match(/Nama Gudang\s*:\s*(.+)$/);
            if (m) header.nama_gudang = m[1].trim();
        }
        if (lineText.includes('Alamat')) {
            const m = lineText.match(/Alamat\s*:\s*(.+)$/);
            if (m) header.alamat = m[1].trim();
        }
        if (lineText.includes('Mitra')) {
            const m = lineText.match(/Mitra\s*:\s*(.+)$/);
            if (m) header.mitra = m[1].trim();
        }
        if (lineText.includes('Lokasi Project')) {
            const m = lineText.match(/Lokasi Project\s*:\s*(.+)$/);
            if (m) header.lokasi_project = m[1].trim();
        }
        if (lineText.includes('Tanggal') && !lineText.includes('No')) {
            const m = lineText.match(/Tanggal\s*(\d{4}-\d{2}-\d{2})/);
            if (m) header.tanggal = m[1];
        }
        if (/^\d{6,10}\s+/.test(lineText)) {
            const m = lineText.match(/^(\d{6,10})\s+(.+)$/);
            if (m) {
                header.nik_petugas = m[1];
                header.nama_petugas = m[2].trim();
            }
        }
        if (lineText.includes('Teknisi')) {
            header.jabatan_petugas = lineText;
        }

        if (lineText.includes('ID Barang') && lineText.includes('Nama Barang')) {
            inTable = true;
            continue;
        }

        if (inTable) {
            if (
                lineText.startsWith('Tanggal') ||
                lineText.includes('Petugas Lapangan') ||
                lineText.includes('Powered by')
            ) {
                inTable = false;
                continue;
            }

            if (lineText === 'Pemakaian') continue;

            rawRows.push(line);
        }
    }

    interface MaterialDraft {
        no: string;
        idParts: string[];
        nameParts: string[];
        satuan: string;
        qty: string;
        keterangan: string;
    }

    const materialList: MaterialDraft[] = [];
    let currentMaterial: MaterialDraft | null = null;

    for (const row of rawRows) {
        const noItem = row.items.find((it) => it.x <= 40 && /^\d+$/.test(it.text));

        if (noItem) {
            if (currentMaterial) materialList.push(currentMaterial);

            const idItem = row.items.find((it) => it.x >= 45 && it.x < 135);
            const nameItem = row.items.find((it) => it.x >= 135 && it.x < 340);
            const satuanItem = row.items.find((it) => it.x >= 340 && it.x < 400);
            const qtyItem = row.items.find((it) => it.x >= 400 && it.x < 480);
            const ketItem = row.items.find((it) => it.x >= 480);

            currentMaterial = {
                no: noItem.text,
                idParts: idItem ? [idItem.text] : [],
                nameParts: nameItem ? [nameItem.text] : [],
                satuan: satuanItem ? satuanItem.text : '',
                qty: qtyItem ? qtyItem.text : '',
                keterangan: ketItem ? ketItem.text : '',
            };
        } else if (currentMaterial) {
            for (const it of row.items) {
                if (it.x >= 45 && it.x < 135) {
                    currentMaterial.idParts.push(it.text);
                } else if (it.x >= 135 && it.x < 340) {
                    currentMaterial.nameParts.push(it.text);
                } else if (it.x >= 340 && it.x < 400 && !currentMaterial.satuan) {
                    currentMaterial.satuan = it.text;
                } else if (it.x >= 400 && it.x < 480 && !currentMaterial.qty) {
                    currentMaterial.qty = it.text;
                } else if (it.x >= 480 && !currentMaterial.keterangan) {
                    currentMaterial.keterangan = it.text;
                }
            }
        }
    }
    if (currentMaterial) materialList.push(currentMaterial);

    const formattedMaterials: BapbPdfMaterial[] = materialList.map((m) => ({
        NO: m.no,
        'ID MATERIAL': m.idParts.join('').replace(/-\s+/g, '-').trim(),
        'NAMA MATERIAL': m.nameParts.join(' ').trim(),
        SATUAN: m.satuan,
        'QTY PEMAKAIAN': String(parseFloat(m.qty.replace(',', '.')) || 0),
        KETERANGAN: m.keterangan,
    }));

    return {
        header,
        materials: formattedMaterials,
    };
}
